const base='http://127.0.0.1:5088/pmo-nav';
async function api(path,body) {
  const response=await fetch(base+'/api/resource-plan'+path,body?{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)}:undefined);
  return {status:response.status,body:await response.json()};
}
